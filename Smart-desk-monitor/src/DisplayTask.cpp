void vTaskUIManager(void *pvParameters) {
    u8g2.begin(); // Khởi động màn hình OLED
    const TickType_t xPeriod = pdMS_TO_TICKS(200);

    for(int i=0 ; i<1; i++){
        digitalWrite(PIN_ALARM_BUZZER, HIGH);
        digitalWrite(PIN_HEARTBEAT_LED, HIGH);
        vTaskDelay(xPeriod);

        digitalWrite(PIN_ALARM_BUZZER, LOW);
        digitalWrite(PIN_HEARTBEAT_LED, LOW);
        if(i!=2)
            vTaskDelay(xPeriod);

    }
    digitalWrite(PIN_HEARTBEAT_LED, HIGH);

    SystemData_t local_data;
    uint8_t Tab_index = 0;
    InputEvent_t ev = EVENT_NONE;

    for (;;) {

        if(xQueueReceive(xQueueInputEvent, &ev, 0) == pdPASS){
            if(ev == EVENT_ROTATE_CW || ev == EVENT_BUTTON_PRESS)
                Tab_index = (Tab_index + 1) % Tab_Number;
            else if(ev == EVENT_ROTATE_CCW){
                    Tab_index = (Tab_index + Tab_Number - 1) % (Tab_Number);
            }
        }

        if (xSemaphoreTake(xMutexData, pdMS_TO_TICKS(20)) == pdTRUE) {
            local_data = g_telemetry;
            xSemaphoreGive(xMutexData);
        }
        u8g2.setBitmapMode(1);
        u8g2.setFontMode(1);

        u8g2.clearBuffer(); // Bắt buộc xóa sạch frame cũ trước khi vẽ frame mới
        
        if(Tab_index == 0){
            u8g2.drawXBM(28, 10, 19, 19, temperature_bits);
            u8g2.drawXBM(89, 10, 13, 19, humidity_bits);


            u8g2.setFont(u8g2_font_helvB12_tr);
    
            char buf[20];
            snprintf(buf, sizeof(buf), "%.1f C", local_data.temperature);
            u8g2.drawStr(10, 50, buf);

            snprintf(buf, sizeof(buf), "%.1f%%", local_data.humidity);
            u8g2.drawStr(80, 50, buf);
        }
        else if(Tab_index == 1){
            if(udp_Started){
                char buf[16];
                u8g2.setFont(u8g2_font_helvB10_tr);

                u8g2.drawStr(14, 21, "CPU");
                u8g2.drawStr(84, 21, "RAM");

                u8g2.setFont(u8g2_font_helvB12_tr);

                snprintf(buf, sizeof(buf), "%d%%", local_data.cpu_usage);
                u8g2.drawStr(16, 45, buf);

                snprintf(buf, sizeof(buf), "%d%%", local_data.ram_usage);
                u8g2.drawStr(86, 45, buf);

                u8g2.drawLine(64, 15, 64, 50);
            }
            else{
                u8g2.drawXBMP(39, 5, 51, 51, NoInternet_bits);
            }
        }
        else if(Tab_index == 2){
            if(udp_Started){
                char buf[16];
                u8g2.setFont(u8g2_font_helvB12_tr);
                u8g2.drawStr(45, 20, "GPU");
            
                u8g2.setFont(u8g2_font_helvB12_tr);
                snprintf(buf, sizeof(buf), "%d%%", local_data.gpu_usage);
                u8g2.drawStr(15, 45, buf);

                snprintf(buf, sizeof(buf), "%d C", local_data.gpu_temp);
                u8g2.drawStr(85, 45, buf);

                u8g2.drawLine(64, 25, 64, 50);
            }
            else{
                u8g2.drawXBMP(39, 5, 51, 51, NoInternet_bits);
            }
        }
        else if(Tab_index == 3){
            u8g2.drawXBMP(45, 10, 38, 38, like_icon_bits);
        }


        for (int i = 0; i < Tab_Number && Tab_index<4; i++) {
            if (i == Tab_index) u8g2.drawDisc(52 + i * 8, 60, 2); // Chấm đặc
            else u8g2.drawCircle(52 + i * 8, 60, 2);                // Vòng tròn rỗng
        }
        
        
        // 4. BẮN TOÀN BỘ 1KB TỪ RAM XUỐNG MÀN HÌNH VẬT LÝ QUA I2C
        u8g2.sendBuffer();

        // Chu kỳ quét khung hình (~20 FPS)
        vTaskDelay(pdMS_TO_TICKS(50));
    }
}